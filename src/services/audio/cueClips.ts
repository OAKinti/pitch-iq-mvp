import type { CoachPersona, CueId } from '../../types/contracts';
import { CUE_TEXT } from '../voice/cueLibrary';

export interface CueClipPlan {
  readonly persona: CoachPersona;
  readonly id: CueId;
  readonly text: string;
  readonly fileName: string;
}

export const CUE_PERSONAS: readonly CoachPersona[] = ['captain', 'drill_sergeant', 'hype'];

export const CUE_IDS: readonly CueId[] = [
  'calibrate_step_back',
  'calibrate_hold_still',
  'ready_go',
  'out_of_frame',
  'back_in_frame',
  'rhythm_good',
  'pace_up',
  'switch_feet',
  'halfway',
  'ten_seconds',
  'final_push',
  'turn_sharp',
  'drill_complete',
];

/** 3 personas x 13 cues = 39 clips; text comes from CUE_TEXT. */
export function planCueClips(): CueClipPlan[] {
  const plan: CueClipPlan[] = [];
  for (const persona of CUE_PERSONAS) {
    for (const id of CUE_IDS) {
      plan.push({ persona, id, text: CUE_TEXT[persona][id], fileName: `${persona}__${id}.mp3` });
    }
  }
  return plan;
}

/** Full source of src/services/audio/cueSources.ts for the given plan. Deterministic, no env data. */
export function renderCueSourcesModule(plan: readonly CueClipPlan[]): string {
  const lines: string[] = [
    "import type { CueSourceMap } from './cuePlayer';",
    '',
    '// GENERATED by scripts/generate-cue-audio.ts - do not edit by hand.',
    'export const CUE_AUDIO_SOURCES: CueSourceMap = {',
  ];
  for (const persona of CUE_PERSONAS) {
    lines.push(`  ${persona}: {`);
    for (const c of plan.filter((p) => p.persona === persona)) {
      lines.push(`    ${c.id}: require('../../../assets/audio/cues/${c.fileName}'),`);
    }
    lines.push('  },');
  }
  lines.push('};', '');
  return lines.join('\n');
}
